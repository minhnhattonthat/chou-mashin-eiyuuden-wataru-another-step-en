"""mktbl.py: write tbl/jp_common.tbl (16-bit LE codes 0x0001-0x01A3, the common font FM16/MSG_CG.BIN) from the charts below.

Code c draws MSG_CG.BIN glyph c + 0xA6 (16x16 4bpp, 128 bytes). Codes >= 0x1A4 are the per-room kanji (FM16/M16_Rxx.BIN),
tabled per room by the extractor. Kanji here are filled from tbl/kanji_common.txt (one 'XXXX=字' per line) when present.
Controls (event-bytecode level) are documented in docs/re/text.md. Run: python -X utf8 tools/mktbl.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# (first code, characters); "_" = unused/blank cell, "?" alone is the literal question mark only where noted.
ROWS = [
    (0x01, "あいうえおかきくけこさしすせそたち"),
    (0x12, "つてとなにぬねのはひふへほまみむ"),
    (0x22, "めもやゆよらりるれろわをんゃゅょ"),
    (0x32, "ぁぃぅぇぉっゔ、。"),
    (0x3C, "がぎぐげござ"),
    (0x42, "じずぜぞだぢづでどばびぶべぼぱぴ"),
    (0x52, "ぷぺぽ"),
    (0x56, "アイウエオカキクケコサシ"),
    (0x62, "スセソタチツテトナニヌネノハヒフ"),
    (0x72, "ヘホマミムメモヤユヨラリルレロワ"),
    (0x82, "ヲンャュョァィゥェォッヴ"),
    (0x91, "ガ"),
    (0x92, "ギグゲゴザジズゼゾダヂヅデドバビ"),
    (0xA2, "ブベボパピプペポ？！ー・"),
    (0xB0, "水雷火"),
    (0xB4, "０１２３４５６７８９"),
    (0xC4, "○×△□／"),
    (0xCB, "＋－×％：．ＡＢＣＤＥＦＧＨＩ"),
    (0xDC, "ＬＭＮＯＰＱＲＳＴＵ"),
]
# Icons and glyphs with no character: written as named tokens so they roundtrip and read clearly.
NAMED = {0x3B: "{k3B}", 0xB3: "{dash}", 0xBE: "{icon_sword}", 0xBF: "{icon_shield}", 0xC0: "{icon_armor}",
         0xC1: "{icon_helm}", 0xC2: "{icon_boots}", 0xC3: "{icon_ring}", 0xC9: "{gC9}", 0xCA: "{gCA}"}


def main():
    m = {}
    for first, chars in ROWS:
        for i, ch in enumerate(chars):
            if ch != "_":
                m[first + i] = ch
    m.update(NAMED)
    kc = ROOT / "tbl" / "kanji_common.txt"
    if kc.exists():
        for line in kc.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.startswith("#"):
                k, v = line.split("=", 1)
                m.setdefault(int(k, 16), v)
    out = ["# Generated by tools/mktbl.py. 16-bit little-endian codes (key = LE bytes). Do not edit by hand."]
    for code in sorted(m):
        out.append("%02X%02X=%s" % (code & 0xFF, code >> 8, m[code]))
    (ROOT / "tbl").mkdir(exist_ok=True)
    (ROOT / "tbl" / "jp_common.tbl").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(len(m), "codes")


if __name__ == "__main__":
    main()
