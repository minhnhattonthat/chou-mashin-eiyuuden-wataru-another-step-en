"""Names (items, skills, enemies, places, mashin, attacks) from the game's tables -> one English form each.

    python -X utf8 tools/names.py            list JP names with more than one English form
    python -X utf8 tools/names.py --apply    unify them (batches.merge --overwrite) and rewrite glossary.md's
                                             generated "## Names from the game tables" section

A name = an entry whose box form is `name` (batches.box), or any entry whose whole JP equals such a name (BALLBAT
menu lists, TTL mashin list). Canonical form: the first English (table priority below) that fits the tightest
limit among every place the name appears; else the shortest. Rows already in the hand-written tables are skipped.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import batches  # noqa: E402

PRIORITY = ["exe_", "fds_", "ENE", "MACHINE", "BALLBAT", "TTL"]
ALIASES = {"かみがみのさばき": "神がみのさばき", "ゆうきのあかし": "勇気のあかし", "りゅうじんすい": "龍神水"}  # battle kana = field kanji
START = "## Names from the game tables"
SECTION = re.compile(r"(?ms)^" + re.escape(START) + r"$.*?(?=^## )")  # headings at line start only
SPEAKERS = re.compile(r"(?m)^## Speakers$")


def rank(stem):
    return next((k for k, p in enumerate(PRIORITY) if stem.startswith(p)), len(PRIORITY))


def collect():
    ents = [(p.stem, e) for p, _, es in batches.docs() for e in es if e.get("en")]
    def key(e):
        k = batches.show(e["jp"]).strip("　").rstrip("！")  # attack shouts end in ！
        return ALIASES.get(k, k)

    names = {key(e) for _, e in ents if batches.box(e)[2] == "name"}
    out = defaultdict(list)  # jp -> [(stem, entry)]
    for stem, e in ents:
        k = key(e)
        if k in names and len(k) >= 2 and "\\n" not in k:
            out[k].append((stem, e))
    return out


def canonical(uses):
    limit = min(batches.box(e)[0] - (1 if e["jp"].endswith("！") else 0) for _, e in uses)
    forms = [e["en"].strip().rstrip("!") for _, e in sorted(uses, key=lambda u: rank(u[0]))]
    fit = [f for f in forms if len(f) <= limit]
    return (fit or sorted(forms, key=len))[0], limit


def main(apply):
    text = SECTION.sub("", batches.GLOSSARY.read_text(encoding="utf-8"))  # the hand-written tables only
    hand = {c.split("|")[1].strip() for c in text.splitlines() if c.startswith("| ") and c.count("|") >= 5}
    hand = {j.strip() for c in hand for j in c.split("/")}
    rows, new = [], {}
    for jp, uses in sorted(collect().items()):
        en, limit = canonical(uses)
        if len({e["en"].strip().rstrip("!") for _, e in uses}) > 1:
            print(f"{jp}: {' / '.join(sorted({e['en'] for _, e in uses}))} -> {en}")
            for _, e in uses:
                want = en + ("!" if e["en"].strip().endswith("!") else "")
                if e["en"] != want:
                    new[e["id"]] = want
        if len(en) > limit:
            print(f"  LONG {jp}: {en!r} > {limit}")
        if jp not in hand and len(jp) >= 3:
            rows.append(f"| {jp} | {en} | {limit} | {','.join(sorted({s for s, _ in uses}))} | |")
    if not apply:
        return
    if new:
        batches.merge(new, True)
    text = SECTION.sub("", batches.GLOSSARY.read_text(encoding="utf-8"))
    section = (f"{START}\n(generated by tools/names.py from the merged tables; change a name in script/ and rerun)\n\n"
               "| JP | EN | max | source | Avoid |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n\n")
    text = SPEAKERS.sub(lambda m: section + m[0], text, count=1)  # just before the real ## Speakers heading
    batches.GLOSSARY.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rows)} glossary rows, {len(new)} entries unified")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main("--apply" in sys.argv)
